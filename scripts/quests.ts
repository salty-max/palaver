/**
 * The quest facts the offer page shows, from wow-data's databases
 * (../wow-data, its pinned sources), each game's own:
 *
 *   addon/Palaver/Quests_Classic.lua, Quests_Forever.lua: each quest's level,
 *     its kind (the client's QuestInfo id: 1 elite, 41 PvP, 62 raid, 81
 *     dungeon...), its place in its chain and the chain's length, packed in
 *     one number by its id (Game.lua's G.facts reads it).
 *   i18n/quest_types.json: the kinds' names in every language the game has,
 *     the client's own (QuestInfo), for scripts/locales.ts to put in each
 *     language's Text file.
 *
 * A chain is the game's own NextQuestInChain, nothing else: a prerequisite
 * is no chain ("Dwarven Outfitters" opens eleven of Coldridge's quests, none
 * of them its part 2). A quest's place: the longest road back to a quest
 * nothing leads into, plus one; the chain's length: that place and the road
 * on (one road: each quest names one next). The Defias Brotherhood: 7 parts.
 *
 *   bun scripts/quests.ts           write them
 *   bun scripts/quests.ts --check   fail if one isn't up to date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type * as WowDb from "../../wow-data/src/db";
import { familyPath } from "./root";

// through the family folder, from a worktree too (scripts/root.ts)
const { openDb } = (await import(familyPath("wow-data", "src", "db.ts"))) as typeof WowDb;

const ROOT = join(import.meta.dir, "..");
const ADDON = join(ROOT, "addon", "Palaver");
type Game = "classic" | "forever";

// the kinds shown (the client's QuestInfo ids; 21, "Life", is none a player sees)
export const KINDS = [1, 41, 62, 81, 82, 83];
const LOCALES = ["enUS", "enGB", "deDE", "frFR", "esES", "esMX", "ruRU", "ptBR", "itIT", "koKR", "zhCN", "zhTW"];
// (a language the database names nothing in: another's, the client's own)
const NAMES_OF: Record<string, string> = { enGB: "enUS" };

export type Fact = { id: number; level: number; kind: number; part: number; of: number };

export function facts(game: Game): Fact[] {
  const db = openDb(game);
  const rows = db.query("SELECT id, level, type, next_in_chain FROM quest WHERE removed IS NOT 1 ORDER BY id").all() as {
    id: number;
    level: number | null;
    type: number | null;
    next_in_chain: number | null;
  }[];
  db.close();
  const ids = new Set(rows.map((r) => r.id));
  const next = new Map<number, number>();
  for (const r of rows) if (r.next_in_chain && r.next_in_chain !== r.id && ids.has(r.next_in_chain)) next.set(r.id, r.next_in_chain);
  const into = new Map<number, number[]>();
  for (const [a, b] of next) into.set(b, [...(into.get(b) ?? []), a]);
  const backMemo = new Map<number, number>();
  const back = (id: number, seen = new Set<number>()): number => {
    const known = backMemo.get(id);
    if (known !== undefined) return known;
    if (seen.has(id)) return 0; // (a loop in the data: cut)
    seen.add(id);
    let best = 0;
    for (const p of into.get(id) ?? []) best = Math.max(best, 1 + back(p, seen));
    seen.delete(id);
    backMemo.set(id, best);
    return best;
  };
  const on = (id: number) => {
    let n = 0;
    const seen = new Set([id]);
    for (let cur = next.get(id); cur !== undefined && !seen.has(cur); cur = next.get(cur)) {
      seen.add(cur);
      n++;
    }
    return n;
  };
  const out: Fact[] = [];
  for (const r of rows) {
    const part = back(r.id) + 1;
    const of = part + on(r.id);
    const level = r.level && r.level > 0 && r.level < 100 ? r.level : 0;
    const kind = r.type && KINDS.includes(r.type) ? r.type : 0;
    if (part > 99 || of > 99) throw new Error(`quest ${r.id}: a chain past 99 (${part} of ${of})`);
    const chained = of > 1;
    if (!level && !kind && !chained) continue;
    out.push({ id: r.id, level, kind, part: chained ? part : 0, of: chained ? of : 0 });
  }
  return out;
}

// level + kind * 100 + part * 10000 + of * 1000000
const pack = (f: Fact) => f.level + f.kind * 100 + f.part * 10000 + f.of * 1000000;

const chunks = (items: string[], n: number) => {
  const out: string[] = [];
  for (let i = 0; i < items.length; i += n) out.push("  " + items.slice(i, i + n).join(", ") + ",");
  return out.join("\n");
};

function lua(game: Game): string {
  return [
    "-- Generated by scripts/quests.ts from wow-data's database: don't edit.",
    "-- Each quest's facts by its id: level + kind * 100 + part * 10000 + of * 1000000",
    "-- (kind: the client's QuestInfo id; part of of: its place in its chain).",
    "local _, ns = ...",
    "",
    "ns.quests = {",
    chunks(
      facts(game).map((f) => `[${f.id}]=${pack(f)}`),
      8,
    ),
    "}",
    "",
  ].join("\n");
}

export function questTypes(): Record<string, Record<string, string>> {
  const db = openDb("forever");
  const out: Record<string, Record<string, string>> = {};
  for (const locale of LOCALES) {
    const rows = db
      .query(`SELECT id, name FROM name WHERE kind = 'quest_info' AND locale = ? AND id IN (${KINDS.join(",")}) ORDER BY id`)
      .all(NAMES_OF[locale] ?? locale) as { id: number; name: string }[];
    const names = Object.fromEntries(rows.map((r) => [String(r.id), r.name.trim()]));
    const missing = KINDS.filter((k) => !names[k]);
    if (missing.length) throw new Error(`${locale}: no name for the quest kinds ${missing.join(", ")}`);
    out[locale] = names;
  }
  db.close();
  return out;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  const files: [string, string][] = [
    [join(ADDON, "Quests_Classic.lua"), lua("classic")],
    [join(ADDON, "Quests_Forever.lua"), lua("forever")],
    [join(ROOT, "i18n", "quest_types.json"), `${JSON.stringify(questTypes(), null, 2)}\n`],
  ];
  for (const [file, text] of files) {
    const name = file.slice(ROOT.length + 1);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
        console.error(`✗ ${name} is out of date: bun scripts/quests.ts`);
        stale = true;
      }
    } else {
      writeFileSync(file, text);
      console.log(`wrote ${name}`);
    }
  }
  if (check && !stale) console.log("✓ quest facts up to date");
  process.exit(stale ? 1 : 0);
}
